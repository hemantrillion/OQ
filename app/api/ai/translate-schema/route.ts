import { NextRequest, NextResponse } from 'next/server';

interface ExtractedSchemaParams {
  business_name?: string;
  business_type?: string;
  stations_count?: number;
  stations?: Array<{ name: string; type: string }>;
  open_time?: string;
  close_time?: string;
  services?: Array<{ name: string; duration_minutes: number; price: number; buffer_minutes?: number }>;
  buffer_minutes?: number;
  is_complete?: boolean;
  missing_fields?: string[];
  conversational_reply_en: string;
  conversational_reply_hi: string;
}

